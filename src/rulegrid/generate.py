"""Files generated from a structure, committed next to it: the profile's JSON Schema, for editors, and
`structure_types.py`, the structure's value ids as Python types. `check` reports them when they drift from
`structure.yaml`. The module is not named `types.py`, which would shadow the standard library's for a script beside it.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from rulegrid.policy import (
    STRUCTURE,
    AxisFile,
    AxisSpec,
    ExampleFile,
    PrincipleFile,
    ProfileFile,
    ProhibitionFile,
    Structure,
    StructureFile,
    TierFile,
    ValueFile,
)

PROFILE_SCHEMA = "profile.schema.json"
TYPES = "structure_types.py"


def _object(properties: dict[str, Any], required: list[str] | None = None) -> dict[str, Any]:
    schema: dict[str, Any] = {"type": "object", "additionalProperties": False, "properties": properties}
    if required:
        schema["required"] = required
    return schema


def _text(model: type[BaseModel], name: str) -> dict[str, Any]:
    """A string field of a profile file model, with its description."""
    return {"type": "string", "description": model.model_fields[name].description}


def _axes(axes: Mapping[str, AxisSpec], side: str) -> dict[str, Any]:
    properties = {}
    for axis_id, spec in axes.items():
        values = _object({v: {"$ref": "#/$defs/ValueFile"} for v in spec.values}, list(spec.values))
        values["description"] = AxisFile.model_fields["values"].description
        fields: dict[str, Any] = {"definition": _text(AxisFile, "definition"), "values": values}
        if side == "response":
            fields["guidance"] = _text(AxisFile, "guidance")
        properties[axis_id] = _object(fields, ["definition", "values"])
    return _object(properties, list(properties))


def _cells(condition: Mapping[str, tuple[str, ...]], depth: int = 0) -> dict[str, Any]:
    keys = list(condition)
    if depth == len(keys):
        return {"$ref": "#/$defs/Cell"}
    covered = list(condition[keys[depth]])
    return _object({v: _cells(condition, depth + 1) for v in covered}, covered)


def profile_schema(structure: Structure) -> dict[str, Any]:
    """The JSON Schema of every profile of a structure, which requires every value, tier and cell."""
    _, top = models_json_schema(
        [(m, "validation") for m in (ExampleFile, ValueFile, ProhibitionFile, PrincipleFile)],
        ref_template="#/$defs/{model}",
    )
    defs = top["$defs"]
    cell = {
        axis_id: {"type": "array", "items": {"enum": list(spec.values)}, "minItems": 1, "uniqueItems": True}
        for axis_id, spec in structure.response_axes.items()
    }
    examples = {"type": "array", "items": {"$ref": "#/$defs/ExampleFile"}, "description": "Exchanges in this cell."}
    defs["Cell"] = _object({**cell, "examples": examples})
    defs["Cell"]["description"] = "Per response axis, the values a response may take; an axis left out allows any."
    tiers = {
        tier_id: _object(
            {
                "label": _text(TierFile, "label"),
                "definition": _text(TierFile, "definition"),
                "instruction": _text(TierFile, "instruction"),
                "cells": {**_cells(condition), "description": TierFile.model_fields["cells"].description},
            },
            ["label", "definition", "instruction", "cells"],
        )
        for tier_id, condition in structure.tiers.items()
    }
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "rulegrid profile",
        **_object(
            {
                "structure": _text(ProfileFile, "structure"),
                "context": _text(ProfileFile, "context"),
                "principles": {"type": "object", "additionalProperties": {"$ref": "#/$defs/PrincipleFile"}},
                "turn_axes": _axes(structure.turn_axes, "turn"),
                "response_axes": _axes(structure.response_axes, "response"),
                "tiers": _object(tiers, list(tiers)),
                "prohibitions": {"type": "object", "additionalProperties": {"$ref": "#/$defs/ProhibitionFile"}},
            },
            ["turn_axes", "response_axes", "tiers"],
        ),
        "$defs": defs,
    }


def structure_schema() -> dict[str, Any]:
    """The JSON Schema of `structure.yaml`, shipped as `rulegrid/schemas/structure.schema.json`."""
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", **StructureFile.model_json_schema()}


def _camel(axis_id: str) -> str:
    return "".join(part.capitalize() for part in axis_id.split("_"))


def types_module(structure: Structure) -> str:
    """`structure_types.py`: a `Literal` per axis, the turn and response values as `TypedDict`s, and a typed `load`."""
    lines = [
        f"# Generated by `rulegrid generate` from {STRUCTURE}. Do not edit.",
        "# ruff: noqa\n# fmt: off",
        *(["from collections.abc import Collection"] if any(a.multi for a in structure.response_axes.values()) else []),
        "from pathlib import Path",
        "from typing import Literal, TypedDict, cast",
        "",
        "import rulegrid",
        "",
    ]
    for axis_id, spec in [*structure.turn_axes.items(), *structure.response_axes.items()]:
        lines.append(f"{_camel(axis_id)} = Literal[{', '.join(json.dumps(v) for v in spec.values)}]")
    for name, axes in (("TurnValues", structure.turn_axes), ("ResponseValues", structure.response_axes)):
        lines += ["", "", f"class {name}(TypedDict):"]
        if not axes:
            lines.append("    pass")
        for axis_id, spec in axes.items():
            kind = f"Collection[{_camel(axis_id)}]" if spec.multi else _camel(axis_id)
            lines.append(f"    {axis_id}: {kind}")
    lines += [
        "",
        "",
        f'STRUCTURE_DIGEST = "{structure.digest}"',
        "",
        "",
        "def load(path: str | Path) -> rulegrid.Policy[TurnValues, ResponseValues]:",
        '    """A profile of this structure. Raises when the structure changed since these types were generated."""',
        "    policy = rulegrid.load(path, digest=STRUCTURE_DIGEST)",
        "    return cast(rulegrid.Policy[TurnValues, ResponseValues], policy)",
        "",
    ]
    return "\n".join(lines)


def generated(structure: Structure) -> dict[str, str]:
    """The generated files of a structure, by name, as they should read."""
    return {
        PROFILE_SCHEMA: json.dumps(profile_schema(structure), indent=2, ensure_ascii=False) + "\n",
        TYPES: types_module(structure),
    }


def generate(structure: Structure) -> list[str]:
    """Write the generated files next to `structure.yaml`, and return the names of those that changed.

    It needs no profile, so a profile can be written against the new schema while it doesn't fit yet.
    """
    changed = []
    for name, text in generated(structure).items():
        path = structure.root / name
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            changed.append(name)
    return changed
