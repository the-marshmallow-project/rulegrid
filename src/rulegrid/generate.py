"""Files generated from a structure, committed next to it: the profile's JSON Schema, for editors, and
`structure_types.py`, the structure's value ids as Python types. `check` reports them when they drift from
`structure.yaml`. The module is not named `types.py`, which would shadow the standard library's for a script beside it.
"""

from __future__ import annotations

import json
from typing import Any

from pydantic.json_schema import models_json_schema

from rulegrid.policy import (
    STRUCTURE,
    Axis,
    ExampleFile,
    Policy,
    PrincipleFile,
    ProhibitionFile,
    StructureFile,
    Tier,
    ValueFile,
)

PROFILE_SCHEMA = "profile.schema.json"
TYPES = "structure_types.py"


def _object(properties: dict[str, Any], required: list[str] | None = None) -> dict[str, Any]:
    schema: dict[str, Any] = {"type": "object", "additionalProperties": False, "properties": properties}
    if required:
        schema["required"] = required
    return schema


def _axes(axes: dict[str, Axis], side: str) -> dict[str, Any]:
    properties = {}
    for axis in axes.values():
        values = _object({v: {"$ref": "#/$defs/ValueFile"} for v in axis.ids}, list(axis.ids))
        fields: dict[str, Any] = {"definition": {"type": "string"}, "values": values}
        if side == "response":
            fields["guidance"] = {"type": "string"}
        properties[axis.id] = _object(fields, ["definition", "values"])
    return _object(properties, list(properties))


def _cells(tier: Tier, depth: int = 0) -> dict[str, Any]:
    keys = list(tier.condition)
    if depth == len(keys):
        return {"$ref": "#/$defs/Cell"}
    covered = list(tier.condition[keys[depth]])
    return _object({v: _cells(tier, depth + 1) for v in covered}, covered)


def profile_schema(policy: Policy) -> dict[str, Any]:
    """The JSON Schema of every profile of the policy's structure, which requires every value, tier and cell."""
    _, top = models_json_schema(
        [(m, "validation") for m in (ExampleFile, ValueFile, ProhibitionFile, PrincipleFile)],
        ref_template="#/$defs/{model}",
    )
    defs = top["$defs"]
    cell = {
        a.id: {"type": "array", "items": {"enum": list(a.ids)}, "minItems": 1, "uniqueItems": True}
        for a in policy.response_axes.values()
    }
    defs["Cell"] = _object({**cell, "examples": {"type": "array", "items": {"$ref": "#/$defs/ExampleFile"}}})
    tiers = {
        t.id: _object(
            {
                "label": {"type": "string"},
                "definition": {"type": "string"},
                "instruction": {"type": "string"},
                "cells": _cells(t),
            },
            ["label", "definition", "instruction", "cells"],
        )
        for t in policy.tiers.values()
    }
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "rulegrid profile",
        **_object(
            {
                "structure": {"type": "string"},
                "context": {"type": "string", "description": "Who the agent is and who it talks to."},
                "principles": {"type": "object", "additionalProperties": {"$ref": "#/$defs/PrincipleFile"}},
                "turn_axes": _axes(dict(policy.turn_axes), "turn"),
                "response_axes": _axes(dict(policy.response_axes), "response"),
                "tiers": _object(tiers, list(tiers)),
                "prohibitions": {"type": "object", "additionalProperties": {"$ref": "#/$defs/ProhibitionFile"}},
            },
            ["turn_axes", "response_axes", "tiers"],
        ),
        "$defs": defs,
    }


def structure_schema() -> dict[str, Any]:
    """The JSON Schema of `structure.yaml`, shipped as `rulegrid/schemas/structure.schema.json`."""
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", **StructureFile.model_json_schema()}


def _camel(axis_id: str) -> str:
    return "".join(part.capitalize() for part in axis_id.split("_"))


def types_module(policy: Policy) -> str:
    """`structure_types.py`: a `Literal` per axis, the turn and response values as `TypedDict`s, and a typed `load`."""
    lines = [
        f"# Generated by `rulegrid generate` from {STRUCTURE}. Do not edit.",
        "# ruff: noqa\n# fmt: off",
        *(["from collections.abc import Collection"] if any(a.multi for a in policy.response_axes.values()) else []),
        "from pathlib import Path",
        "from typing import Literal, TypedDict, cast",
        "",
        "import rulegrid",
        "",
    ]
    for axis in [*policy.turn_axes.values(), *policy.response_axes.values()]:
        lines.append(f"{_camel(axis.id)} = Literal[{', '.join(json.dumps(v) for v in axis.ids)}]")
    for name, axes in (("TurnValues", policy.turn_axes), ("ResponseValues", policy.response_axes)):
        lines += ["", "", f"class {name}(TypedDict):"]
        for axis in axes.values():
            kind = f"Collection[{_camel(axis.id)}]" if axis.multi else _camel(axis.id)
            lines.append(f"    {axis.id}: {kind}")
    lines += [
        "",
        "",
        f'STRUCTURE_DIGEST = "{policy.structure_digest}"',
        "",
        "",
        "def load(path: str | Path) -> rulegrid.Policy[TurnValues, ResponseValues]:",
        '    """A profile of this structure. Raises when the structure changed since these types were generated."""',
        "    policy = rulegrid.load(path, digest=STRUCTURE_DIGEST)",
        "    return cast(rulegrid.Policy[TurnValues, ResponseValues], policy)",
        "",
    ]
    return "\n".join(lines)


def generated(policy: Policy) -> dict[str, str]:
    """The generated files of the policy's structure, by name, as they should read."""
    return {
        PROFILE_SCHEMA: json.dumps(profile_schema(policy), indent=2, ensure_ascii=False) + "\n",
        TYPES: types_module(policy),
    }


def generate(policy: Policy) -> list[str]:
    """Write the generated files next to the policy's `structure.yaml`, and return the names of those that changed."""
    changed = []
    for name, text in generated(policy).items():
        path = policy.root / name
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            changed.append(name)
    return changed
